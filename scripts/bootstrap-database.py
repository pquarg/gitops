#!/usr/bin/env python3
"""User-run initialization of this project's private RDS application login.

Requires Python 3, AWS CLI and kubectl. Passwords travel through subprocess stdin,
never command arguments or local files. The administrator password is not stored
in Kubernetes; only the application's connection Secret is persisted.
"""

import argparse
import base64
import json
from pathlib import Path
import secrets
import shutil
import subprocess
import sys
from urllib.parse import parse_qs, quote, unquote, urlsplit


PROJECT_ID = "245361883993"
REGION = "eu-north-1"
CLUSTER = "deployment-project-dev"
DATABASE_ID = "deployment-project-dev-postgres"
APP = "myfastapiapp"
APP_SECRET = "myfastapiapp-secrets"

BOOTSTRAP_SQL = r"""
\getenv app_password APP_PASSWORD
SELECT 'CREATE ROLE myfastapiapp LOGIN'
WHERE NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'myfastapiapp')
\gexec
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'myfastapiapp'
               AND (rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication
                    OR rolbypassrls)) THEN
        RAISE EXCEPTION 'Existing application login has elevated privileges; review before bootstrap';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_auth_members
               WHERE member = (SELECT oid FROM pg_roles WHERE rolname = 'myfastapiapp')) THEN
        RAISE EXCEPTION 'Application login has role memberships; review before bootstrap';
    END IF;
END $$;
ALTER ROLE myfastapiapp WITH LOGIN PASSWORD :'app_password';
GRANT CONNECT ON DATABASE myfastapiapp TO myfastapiapp;
GRANT USAGE, CREATE ON SCHEMA public TO myfastapiapp;
"""

VERIFY_SQL = r"""
DO $$
BEGIN
    IF current_user <> 'myfastapiapp' OR current_database() <> 'myfastapiapp' THEN
        RAISE EXCEPTION 'Unexpected database or application login';
    END IF;
    IF NOT (SELECT ssl FROM pg_stat_ssl WHERE pid = pg_backend_pid()) THEN
        RAISE EXCEPTION 'TLS is not active';
    END IF;
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = current_user
               AND (rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication
                    OR rolbypassrls)) THEN
        RAISE EXCEPTION 'Application login has unexpected elevated privileges';
    END IF;
END $$;
BEGIN;
CREATE TABLE public.__deployment_bootstrap_probe (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text
);
ALTER TABLE public.__deployment_bootstrap_probe ADD COLUMN extra text;
CREATE INDEX __deployment_bootstrap_probe_value_idx
    ON public.__deployment_bootstrap_probe (value);
INSERT INTO public.__deployment_bootstrap_probe (value) VALUES ('probe');
DROP TABLE public.__deployment_bootstrap_probe;
ROLLBACK;
SELECT 'BOOTSTRAP_OK login=myfastapiapp database=myfastapiapp tls=' || version
    FROM pg_stat_ssl WHERE pid = pg_backend_pid() AND ssl;
"""


def app_credentials(existing, host):
    """Reuse this database's existing app password; refuse an unrelated Secret."""
    if existing:
        try:
            url = base64.b64decode(
                existing["data"]["AUTH_DATABASE_URL"], validate=True
            ).decode()
            parsed = urlsplit(url)
            password = unquote(parsed.password or "")
            valid = (
                parsed.scheme == "postgresql"
                and parsed.username == APP
                and parsed.hostname == host
                and parsed.port == 5432
                and parsed.path == f"/{APP}"
                and parse_qs(parsed.query) == {"sslmode": ["verify-full"]}
                and password
                and "\n" not in password
                and "\r" not in password
            )
        except (KeyError, ValueError, UnicodeError):
            valid = False
        if not valid:
            raise RuntimeError(
                "Existing app Secret does not match this database and verify-full "
                "TLS. Review it locally before continuing; it was not changed."
            )
        return url, password
    password = secrets.token_urlsafe(32)
    url = (
        f"postgresql://{APP}:{quote(password, safe='')}@{host}:5432/{APP}"
        "?sslmode=verify-full"
    )
    return url, password


def client_pod(name, host):
    return {
        "apiVersion": "v1",
        "kind": "Pod",
        "metadata": {"name": name, "namespace": APP},
        "spec": {
            "restartPolicy": "Never",
            "activeDeadlineSeconds": 600,
            "automountServiceAccountToken": False,
            "securityContext": {
                "runAsNonRoot": True, "runAsUser": 10001, "runAsGroup": 10001,
                "seccompProfile": {"type": "RuntimeDefault"},
            },
            "containers": [{
                "name": "postgres-client",
                "image": "docker.io/library/postgres:17-alpine",
                "command": ["sleep", "600"],
                "securityContext": {
                    "allowPrivilegeEscalation": False,
                    "readOnlyRootFilesystem": True,
                    "capabilities": {"drop": ["ALL"]},
                },
                "env": [{"name": k, "value": v} for k, v in {
                    "PGHOST": host, "PGPORT": "5432", "PGDATABASE": APP,
                    "PGSSLMODE": "verify-full", "PGCONNECT_TIMEOUT": "15",
                    "PGSSLROOTCERT": "/etc/rds-ca/global-bundle.pem",
                }.items()],
                "resources": {
                    "requests": {"cpu": "50m", "memory": "32Mi"},
                    "limits": {"cpu": "250m", "memory": "128Mi"},
                },
                "volumeMounts": [{
                    "name": "ca", "mountPath": "/etc/rds-ca", "readOnly": True,
                }],
            }],
            "volumes": [{"name": "ca", "configMap": {"name": name}}],
        },
    }


class Commands:
    def __init__(self, context, profile):
        self.kubectl = ["kubectl", "--context", context]
        self.aws = ["aws", "--profile", profile, "--region", REGION,
                    "--no-cli-pager", "--output", "json"]
        self.redactions = []

    def run(self, argv, *, stdin=None, sensitive=False):
        result = subprocess.run(argv, input=stdin, text=True, capture_output=True)
        if result.returncode:
            # Secret-bearing API errors can echo input, including base64 values.
            detail = "Sensitive command failed; its output was suppressed."
            if not sensitive:
                detail = result.stderr.strip() or result.stdout.strip()
                for value in self.redactions:
                    detail = detail.replace(value, "<REDACTED>")
            raise RuntimeError(f"{argv[0]} failed: {detail}")
        return result.stdout

    def kube(self, *args, **kwargs):
        return self.run([*self.kubectl, *args], **kwargs)

    def aws_json(self, *args, **kwargs):
        return json.loads(self.run([*self.aws, *args], **kwargs))

    def create(self, resource, *, sensitive=False):
        self.kube("create", "-f", "-", stdin=json.dumps(resource), sensitive=sensitive)

    def execute_sql(self, pod, user, password, sql, app_password=None):
        # Read passwords before handing the rest of stdin to psql. No shell
        # tracing, psql query echo, credential arguments, or credential files.
        shell = "set -eu; IFS= read -r PGPASSWORD; export PGPASSWORD; "
        payload = password + "\n"
        if app_password is not None:
            shell += "IFS= read -r APP_PASSWORD; export APP_PASSWORD; "
            payload += app_password + "\n"
        shell += (
            'exec psql -X -w -qAt --set=ON_ERROR_STOP=1 --set=ECHO=none '
            '--set=ECHO_HIDDEN=off --set=VERBOSITY=terse --username="$1"'
        )
        return self.kube(
            "-n", APP, "exec", "-i", pod, "--", "sh", "-c", shell, "sh", user,
            stdin=payload + sql, sensitive=app_password is not None,
        )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("context", help="Explicit EKS kubectl context")
    parser.add_argument("--profile", default="aws-project")
    args = parser.parse_args()
    for executable in ("aws", "kubectl"):
        if not shutil.which(executable):
            parser.error(f"{executable} must be installed")
    commands = Commands(args.context, args.profile)
    temporary = []
    try:
        identity = commands.aws_json("sts", "get-caller-identity")
        if identity["Account"] != PROJECT_ID:
            raise RuntimeError("AWS profile targets a different project; stopping.")
        cluster = commands.aws_json("eks", "describe-cluster", "--name", CLUSTER)["cluster"]
        context = json.loads(commands.kube("config", "view", "--minify", "-o", "json"))
        if context["clusters"][0]["cluster"]["server"] != cluster["endpoint"]:
            raise RuntimeError("Kubectl context does not target this EKS cluster; stopping.")
        db = commands.aws_json(
            "rds", "describe-db-instances", "--db-instance-identifier", DATABASE_ID
        )["DBInstances"][0]
        if (db["DBInstanceStatus"] != "available" or db["PubliclyAccessible"]
                or db["DBName"] != APP or db["Endpoint"]["Port"] != 5432):
            raise RuntimeError("Expected private, available application database; stopping.")
        host = db["Endpoint"]["Address"]
        ca = (Path(__file__).resolve().parents[1] / "apps" / APP / "overlays" / "aws" / "certs"
              / "global-bundle.pem").read_text()
        print("Verified AWS project, EKS context and private RDS instance.", flush=True)

        if not commands.kube("get", "namespace", APP, "--ignore-not-found", "-o", "name").strip():
            commands.create({"apiVersion": "v1", "kind": "Namespace", "metadata": {"name": APP}})
        existing = commands.kube(
            "-n", APP, "get", "secret", APP_SECRET, "--ignore-not-found", "-o", "json",
            sensitive=True,
        )
        url, password = app_credentials(json.loads(existing) if existing.strip() else None, host)
        commands.redactions.extend([password, url])
        if not existing.strip():
            commands.create({
                "apiVersion": "v1", "kind": "Secret", "type": "Opaque",
                "metadata": {"name": APP_SECRET, "namespace": APP},
                "stringData": {"AUTH_DATABASE_URL": url},
            }, sensitive=True)
        print("Application connection Secret is ready; retries reuse its password.", flush=True)

        admin = json.loads(commands.aws_json(
            "secretsmanager", "get-secret-value", "--secret-id",
            db["MasterUserSecret"]["SecretArn"], sensitive=True,
        )["SecretString"])
        admin_password = admin["password"]
        commands.redactions.append(admin_password)
        if (admin["username"] != db["MasterUsername"] or not admin_password
                or "\n" in admin_password or "\r" in admin_password):
            raise RuntimeError("Unexpected administrator Secret format; stopping.")
        name = "myfastapiapp-db-bootstrap-" + secrets.token_hex(4)
        temporary.append(("configmap", name))
        commands.create({
            "apiVersion": "v1", "kind": "ConfigMap",
            "metadata": {"name": name, "namespace": APP},
            "data": {"global-bundle.pem": ca},
        })
        temporary.append(("pod", name))
        commands.create(client_pod(name, host))
        print("Waiting for the temporary PostgreSQL client...", flush=True)
        commands.kube("-n", APP, "wait", "--for=condition=Ready", f"pod/{name}", "--timeout=180s")
        # The administrator changes commit together; the app's DDL probe rolls back.
        print("Initializing the restricted database login and schema grants...", flush=True)
        commands.execute_sql(name, admin["username"], admin_password,
                             "BEGIN;\n" + BOOTSTRAP_SQL + "\nCOMMIT;\n", password)
        print("Verifying the application password, TLS and migration permissions...", flush=True)
        verification = commands.execute_sql(name, APP, password, VERIFY_SQL)
        success = [line for line in verification.splitlines() if line.startswith("BOOTSTRAP_OK ")]
        if len(success) != 1:
            raise RuntimeError("Application verification did not return its success marker.")
        print(success[0])
        print("Schema create/alter/index/insert/drop probe passed and was rolled back.")
        print("Alembic migrations have not been run; they remain part of the Argo CD sync.")
        return 0
    except (RuntimeError, OSError, KeyError, ValueError) as error:
        # Avoid tracebacks containing secret-bearing command input or responses.
        message = str(error)
        for value in commands.redactions:
            message = message.replace(value, "<REDACTED>")
        print(f"Bootstrap failed: {message}", file=sys.stderr)
        print("The app Secret is retained for retry; do not delete it to generate a new password.",
              file=sys.stderr)
        return 1
    finally:
        for kind, name in reversed(temporary):
            try:
                commands.kube("-n", APP, "delete", kind, name, "--ignore-not-found",
                              "--wait=true", "--timeout=60s")
            except (RuntimeError, OSError):
                print(f"Cleanup needed: kubectl --context {args.context} -n {APP} "
                      f"delete {kind} {name}", file=sys.stderr)


if __name__ == "__main__":
    sys.exit(main())
