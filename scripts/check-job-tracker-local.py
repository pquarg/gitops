#!/usr/bin/env python3
"""Probe the external local DB from a Pod with the selected app image and Secret."""
import argparse
import copy
import json
import os
from pathlib import Path
import subprocess
import uuid

ROOT = Path(__file__).resolve().parents[1]
PROBE = r"""
import os
import psycopg
with psycopg.connect(os.environ['JT_DATABASE_URL'].replace('postgresql+psycopg://', 'postgresql://', 1), connect_timeout=10) as conn:
    with conn.cursor() as cursor:
        cursor.execute('SELECT current_user, current_database()')
        if cursor.fetchone() != ('job_tracker', 'job_tracker'):
            raise RuntimeError('Unexpected database or app login')
        cursor.execute('SELECT rolsuper OR rolcreatedb OR rolcreaterole OR rolreplication OR rolbypassrls FROM pg_roles WHERE rolname = current_user')
        if cursor.fetchone()[0]:
            raise RuntimeError('App login has elevated privileges')
        cursor.execute('SELECT count(*) FROM pg_auth_members WHERE member = (SELECT oid FROM pg_roles WHERE rolname = current_user)')
        if cursor.fetchone()[0]:
            raise RuntimeError('App login has unexpected role memberships')
        cursor.execute('CREATE TABLE public.__deployment_bootstrap_probe (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, value text)')
        cursor.execute('CREATE INDEX ON public.__deployment_bootstrap_probe (value)')
        cursor.execute("INSERT INTO public.__deployment_bootstrap_probe (value) VALUES ('probe')")
        cursor.execute('SELECT value FROM public.__deployment_bootstrap_probe')
        if cursor.fetchone() != ('probe',):
            raise RuntimeError('Data probe failed')
        cursor.execute('DROP TABLE public.__deployment_bootstrap_probe')
    conn.rollback()
from job_tracker.parsing import extract
assert extract(b'Synthetic sandbox preflight', 'preflight.txt')['passages'][0]['text'] == 'Synthetic sandbox preflight'
print('Database connectivity, app privileges, transactional DDL and sandboxed parsing passed.')
"""


def make_job(pod_spec, name):
    spec = copy.deepcopy(pod_spec)
    spec['restartPolicy'] = 'Never'
    container = spec['containers'][0]
    container['name'] = 'check'
    container['command'] = ['python', '-c', PROBE]
    # Only the connection Secret is needed; no ConfigMap or deployed API required.
    container.pop('env', None)
    container['envFrom'] = [{'secretRef': {'name': 'job-tracker-secrets'}}]
    for key in ('args', 'ports', 'readinessProbe', 'livenessProbe', 'startupProbe'):
        container.pop(key, None)
    return {
        'apiVersion': 'batch/v1', 'kind': 'Job',
        'metadata': {'name': name, 'namespace': 'job-tracker'},
        'spec': {'backoffLimit': 0, 'activeDeadlineSeconds': 90,
                 'template': {'spec': spec}},
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--environment', required=True, choices=['local'])
    parser.add_argument('--context', required=True)
    parser.add_argument('--kubeconfig', default=os.environ.get('KUBECONFIG', str(Path.home() / '.kube/config')))
    args = parser.parse_args()
    if not args.context.startswith('kind-'):
        parser.error('Local database checks require an explicit kind-* context')
    if ':' in args.kubeconfig:
        parser.error('Select one kubeconfig file with --kubeconfig')
    # Local rendering never contacts the API server or reads filled Secret files.
    rendered = subprocess.check_output([
        'kubectl', 'patch', '--local', '-k',
        str(ROOT / 'apps/job-tracker/overlays/local'),
        '--type=merge', '-p', '{}', '-o', 'json'], text=True)
    decoder = json.JSONDecoder()
    resources = []
    rendered = rendered.lstrip()
    while rendered:
        resource, end = decoder.raw_decode(rendered)
        resources.extend(resource['items'] if resource['kind'] == 'List' else [resource])
        rendered = rendered[end:].lstrip()
    deployment = next(r for r in resources if r['kind'] == 'Deployment' and r['metadata']['name'] == 'job-tracker-worker')
    name = 'local-db-check-' + uuid.uuid4().hex[:12]
    job = make_job(deployment['spec']['template']['spec'], name)
    kube = ['kubectl', '--kubeconfig', args.kubeconfig, '--context', args.context,
            '--namespace', 'job-tracker', '--request-timeout=30s']
    subprocess.run(kube + ['create', '-f', '-'], input=json.dumps(job), text=True, check=True)
    try:
        result = subprocess.run(kube + ['wait', '--for=condition=complete', 'job/' + name, '--timeout=120s'])
        subprocess.run(kube + ['logs', 'job/' + name], check=True)
        result.check_returncode()
    finally:
        subprocess.run(kube + ['delete', 'job', name, '--wait=false'], check=True)


if __name__ == '__main__':
    main()
